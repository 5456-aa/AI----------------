def _write(items, prefix, batch, track, out_root):
    out_dir = out_root / track
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for i, (source, title, content, pub, heat) in enumerate(items, 1):
        rows.append({
            "source": source,
            "source_category": SRC[source],
            "url": f"https://example.com/demo/{track}/{i}",
            "title": title,
            "content": content,
            "published_at": pub,
            "heat": heat,
            "record_id": f"{prefix}{i:05d}",
            "batch": batch,
            "collected_at": "2026-11-11T20:00:00+08:00",
        })
    path = out_dir / "demo.jsonl"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"[{track}] 写入 {len(rows)} 条演示记录 -> {path}")


